//------------------------------------------------------------------------------
// File: billboard.fs
//
// Purpose: Fragment shader for billboard
//------------------------------------------------------------------------------

//------------------------------------------------------------------------------
// Structures
//------------------------------------------------------------------------------
struct Fragment
{
	float4 pos	: SV_POSITION;
	float2 tex	: TEXCOORD0;
};

//------------------------------------------------------------------------------
// Resources
//------------------------------------------------------------------------------
Texture2D	texTexture;

//------------------------------------------------------------------------------
// Samplers
//------------------------------------------------------------------------------
SamplerState 	samTexture;

//------------------------------------------------------------------------------
// Entry point
//------------------------------------------------------------------------------
float4 main( Fragment fragment ) : SV_TARGET
{
	return texTexture.Sample(samTexture, fragment.tex);
}
